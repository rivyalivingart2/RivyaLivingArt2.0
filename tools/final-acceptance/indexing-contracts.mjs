import assert from 'node:assert/strict';
import {qa,record,fingerprint} from '../c6-acceptance/common.mjs';
assert.equal(qa.RIVYA_QA_TARGET,'local');
process.env.DATABASE_URL=qa.DATABASE_URL;
process.env.RIVYA_ENV='production';
process.env.VERCEL_ENV='production';
process.env.SITE_INDEXABLE='true';
const before=await fingerprint();
const {default:sitemap}=await import('../../src/app/sitemap.ts');
const {default:robots}=await import('../../src/app/robots.ts');
const {routeMetadata}=await import('../../src/lib/site-metadata.ts');
const {default:config}=await import('../../next.config.ts');
const map=await sitemap(),paths=map.map(e=>new URL(e.url).pathname);
assert.ok(paths.includes('/')&&paths.includes('/pieces/river-channel'));
for(const route of ['/search','/studio/site-copy','/saved-pieces','/commission/customize','/portfolio'])assert.ok(!paths.includes(route),route);
assert.equal(new Set(paths).size,paths.length);
assert.equal((await routeMetadata('/collectible-design')).robots.index,true);
assert.equal((await routeMetadata('/search')).robots.index,false);
assert.equal((await routeMetadata('/missing-page')).robots.index,false);
assert.equal(robots().sitemap,'https://www.rivyalivingart.com/sitemap.xml');
const headers=await config.headers();
assert.ok(!headers.find(h=>h.source==='/:path*').headers.some(h=>h.key==='X-Robots-Tag'));
assert.ok(headers.some(h=>h.source==='/studio/:path*'&&h.headers.some(v=>v.key==='X-Robots-Tag')));
process.env.VERCEL_ENV='preview';
assert.deepEqual(await sitemap(),[]);
assert.deepEqual(robots().rules,{userAgent:'*',disallow:'/'});
assert.equal((await routeMetadata('/collectible-design')).robots.index,false);
process.env.VERCEL_ENV='production';
process.env.SITE_INDEXABLE='false';
assert.deepEqual(await sitemap(),[]);
assert.deepEqual(robots().rules,{userAgent:'*',disallow:'/'});
assert.deepEqual(await fingerprint(),before);
record('local-indexing-contracts',{at:new Date().toISOString(),environment:'Source-only loopback PostgreSQL; no production setting changed',productionSitemapUrls:paths.length,excluded:['search','Studio site copy','saved pieces','customization','unapproved portfolio'],previewAndHold:'closed',checks:19});
console.log('19 local indexing policy checks passed');
