import assert from 'node:assert/strict';
import {randomUUID,randomBytes,createHash} from 'node:crypto';
import {mkdir,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {localTarget} from './old-design-migration/guard.mjs';
import {registerHooks} from 'node:module';
assert.equal(globalThis.__rivyaMigrationLocalSql,true);
assert.equal(process.env.RIVYA_DATA_MODE,'isolated');
registerHooks({resolve(specifier,context,next){return specifier==='server-only'?{url:'data:text/javascript,export%20{}',shortCircuit:true}:next(specifier,context);}});
const {requestStudioAccess,listAccessRequests,decideAccessRequest,redeemAccessLink}=await import('../src/lib/studio-access.ts');
const {authenticateStaff,createStudioSession,studioSessionFromToken}=await import('../src/lib/studio-auth.ts');
const {default:pg}=await import(pathToFileURL(process.env.RIVYA_MIGRATION_PG_MODULE).href);
const client=new pg.Client(localTarget);await client.connect();
const login='access-qa-'+randomUUID().slice(0,8),password=randomBytes(24).toString('base64url'),nextPassword=randomBytes(24).toString('base64url');
const owner={adminId:process.env.STUDIO_ADMIN_ID,role:'admin',staffId:null};
const report={scope:'Isolated localhost synthetic access account only; no original records changed',login,checks:[]};
const check=(name,value)=>{assert.ok(value,name);report.checks.push(name);};
const current=async(kind='access')=>(await listAccessRequests()).find(r=>r.login===login&&r.kind===kind);
let staffId;
try{
 const input={kind:'access',login,name:'LOCAL QA — fictional access request',contact:'no-contact@example.invalid'};
 await requestStudioAccess(input);await requestStudioAccess({...input,name:'Duplicate must not overwrite'});
 let r=await current();check('Public duplicate does not overwrite request',r.name===input.name);
 check('Request alone creates no staff account',(await client.query('SELECT id FROM rivya_staff WHERE login=$1',[login])).rowCount===0);
 await assert.rejects(()=>decideAccessRequest({...owner,role:'editor'},r.id,r.version,'approve'));check('Non-admin service approval denied',true);
 check('Stale decision rejected',await decideAccessRequest(owner,r.id,r.version+1,'approve')===null);
 let issued=await decideAccessRequest(owner,r.id,r.version,'approve');check('Admin approval issues a link',!!issued?.token);
 let member=(await client.query('SELECT id,role,active,version FROM rivya_staff WHERE login=$1',[login])).rows[0];staffId=member.id;
 check('Approved new account disabled and editor only',!member.active&&member.role==='editor');
 check('No sign-in before password setup',await authenticateStaff(login,password)===null);
 const stored=(await client.query('SELECT token_hash,expires_at FROM rivya_access_requests WHERE id=$1',[r.id])).rows[0];
 check('Only hash stored',stored.token_hash===createHash('sha256').update(issued.token).digest('hex'));
 check('Expiry bounded to thirty minutes',new Date(stored.expires_at)-Date.now()<=30*60000);
 check('Queue never exposes hashes or token',!(JSON.stringify(await listAccessRequests()).includes(issued.token))&&!('token_hash' in (await current())));
 const first=issued.token;r=await current();issued=await decideAccessRequest(owner,r.id,r.version,'approve');
 check('Reissue invalidates original link',await redeemAccessLink(first,password)===false);
 check('Short password refused',await redeemAccessLink(issued.token,'short')===false);
 const race=await Promise.all([redeemAccessLink(issued.token,password),redeemAccessLink(issued.token,password)]);
 check('Concurrent redemption succeeds exactly once',race.filter(Boolean).length===1);
 check('Replayed token denied',await redeemAccessLink(issued.token,password)===false);
 const identity=await authenticateStaff(login,password);check('Approved password enables editor sign-in',identity?.role==='editor');
 const sessionToken=await createStudioSession(identity);check('New session valid',!!await studioSessionFromToken(sessionToken));
 await requestStudioAccess({...input,kind:'recovery'});r=await current('recovery');
 check('Recovery request leaves password valid',!!await authenticateStaff(login,password));
 check('Staff cannot approve own reset',await decideAccessRequest({...owner,adminId:login,staffId},r.id,r.version,'approve')===null);
 issued=await decideAccessRequest(owner,r.id,r.version,'approve');
 await client.query("UPDATE rivya_access_requests SET expires_at=now()-interval '1 second' WHERE id=$1",[r.id]);
 check('Expired link denied',await redeemAccessLink(issued.token,nextPassword)===false);
 r=await current('recovery');issued=await decideAccessRequest(owner,r.id,r.version,'approve');
 check('Recovery password saved',await redeemAccessLink(issued.token,nextPassword));
 check('Old password invalid',await authenticateStaff(login,password)===null);
 check('New password valid',!!await authenticateStaff(login,nextPassword));
 check('Old sessions revoked',await studioSessionFromToken(sessionToken)===null);
 check('Recovery preserves role',(await authenticateStaff(login,nextPassword)).role==='editor');
 await requestStudioAccess({...input,kind:'recovery'});r=await current('recovery');issued=await decideAccessRequest(owner,r.id,r.version,'approve');
 await client.query('UPDATE rivya_staff SET version=version+1 WHERE id=$1',[staffId]);
 check('Admin credential change invalidates issued link',await redeemAccessLink(issued.token,password)===false);
 r=await current('recovery');await decideAccessRequest(owner,r.id,r.version,'reject');check('Rejected request leaves open queue',!await current('recovery'));
 await client.query('UPDATE rivya_staff SET active=false,version=version+1 WHERE id=$1',[staffId]);
 await requestStudioAccess({...input,kind:'recovery'});r=await current('recovery');
 check('Recovery cannot reactivate disabled staff',await decideAccessRequest(owner,r.id,r.version,'approve')===null);
 await decideAccessRequest(owner,r.id,r.version,'reject');
 await requestStudioAccess({...input,kind:'access'});r=await current();
 check('Registration cannot take over existing login',await decideAccessRequest(owner,r.id,r.version,'approve')===null);await decideAccessRequest(owner,r.id,r.version,'reject');
 const ownerInput={...input,login:process.env.STUDIO_ADMIN_ID,kind:'recovery'};
 await requestStudioAccess(ownerInput);const ownerRequest=(await listAccessRequests()).find(r=>r.login===ownerInput.login&&r.kind==='recovery');
 check('Hosting owner cannot reset through staff flow',await decideAccessRequest(owner,ownerRequest.id,ownerRequest.version,'approve')===null);await decideAccessRequest(owner,ownerRequest.id,ownerRequest.version,'reject');
 check('Synthetic account ends disabled',(await client.query('SELECT active FROM rivya_staff WHERE id=$1',[staffId])).rows[0].active===false);
}finally{
 if(staffId)await client.query('UPDATE rivya_staff SET active=false WHERE id=$1 AND login=$2',[staffId,login]);
 report.staffId=staffId;await mkdir('test-results/studio-access',{recursive:true});await writeFile('test-results/studio-access/security.json',JSON.stringify(report,null,2));await client.end();
 console.log(JSON.stringify({checks:report.checks.length,scope:report.scope,completed:report.checks}));
}
